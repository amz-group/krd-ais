const LanguageContext = createContext({ lang: 'ku', setLang: () => {}, t: (k) => k, dir: 'rtl' });

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('krd-lang') || 'ku');
  const dir = lang === 'en' ? 'ltr' : 'rtl';
  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = lang === 'ku' ? 'ckb' : lang;
    localStorage.setItem('krd-lang', lang);
  }, [lang, dir]);
  const t = (key) => dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  return (
    <LanguageContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLang = () => useContext(LanguageContext);